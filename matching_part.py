"""Matching parts without a language model: a cover or a spacer/gasket for a built part.

Everything comes from the original's top-face profile (build_worker.profile: outline, holes, thickness),
so a winning program, a repair, an applied completion and the measured-shape fallback are all handled the
same way. The program is written with partkit: thickness, outline offset (spacer) and one diameter per
group of equal round holes are named parameters; hole positions and the outline are fixed data, because
they are what must line up with the original. Curved edges arrive as the profile's points (0.01 mm).
"""
import math

from adapter_place import MIN_WALL_MM
from design_intent import parameters as program_parameters

KINDS = {"cover": "Cover", "spacer": "Spacer / gasket"}
SPACER_THICKNESS_MM = 1.0
OFFSET_LIMIT_MM = 10.0  # the outline offset slider runs from -limit to +limit
MIN_THICKNESS_MM = 0.1
MAX_THICKNESS_MM = 10.0  # or twice the default, if that is more
EDGE_MARGIN_MAX_MM = 10.0  # or twice the default, if that is more
ALIGNED_WITHIN_MM = 0.05  # a hole counts as aligned when its center is this close to the original's


def split_warning(pieces):
    """Warning when a gasket outline_offset splits the part into computed `pieces` pieces."""
    return f"Gasket splits into {pieces} pieces at this offset — try a smaller offset."


def _point(point):
    return f"({point[0]!r}, {point[1]!r})"


def _points(name, points):
    return [f"{name} = [", *[f"    {_point(p)}," for p in points], "]", ""]


def matching_source(profile, kind, display_name="matching part"):
    """The CadQuery program (text) of a matching part for the part with this top-face profile."""
    groups = {}  # diameter -> centers of the round holes sharing it
    for hole in profile["holes"]:
        if hole["type"] == "circle":
            groups.setdefault(hole["diameter"], []).append(hole["center"])
    shaped = [hole["points"] for hole in profile["holes"] if hole["type"] != "circle"]

    thickness = profile["thickness"] if kind == "cover" else SPACER_THICKNESS_MM
    arguments = [f"    thickness={thickness!r},"]
    data = _points("OUTLINE", profile["outline"])
    if kind == "cover":
        body = ["    part = pk.outline_from_points(OUTLINE, thickness)"]
    else:
        arguments.append("    outline_offset=0.0,")
        body = ["    part = pk.offset_outline(OUTLINE, outline_offset, thickness)"]
    for i, (diameter, centers) in enumerate(groups.items(), 1):
        parameter = "hole_diameter" if len(groups) == 1 else f"hole_diameter_{i}"
        arguments.append(f"    {parameter}={diameter!r},")
        data += _points(f"ROUND_HOLES_{i}", centers)
        body.append(f"    part = pk.hole_pattern(part, ROUND_HOLES_{i}, {parameter})")
    if shaped:
        data += ["SHAPED_HOLES = [", *[f"    [{', '.join(map(_point, points))}]," for points in shaped], "]", ""]
        body += ["    for corners in SHAPED_HOLES:", "        part = pk.cut_polygon(part, corners)"]
    return "\n".join([
        f'"""{display_name}: {KINDS[kind]} of the original part. Generated by matching_part.py from its top face."""',
        "import partkit as pk",
        "",
        *data,
        "",
        "def build_part(",
        *arguments,
        "):",
        *body,
        "    return part",
        "",
    ])


def slider_parameters(source):
    """A matching program's named parameters; those a default alone cannot range get "min" and "max"."""
    result = []
    for name, value in program_parameters(source):
        parameter = {"name": name, "default": value}
        if name == "thickness":
            parameter.update(min=MIN_THICKNESS_MM, max=max(MAX_THICKNESS_MM, 2 * value))
        elif name == "outline_offset":
            parameter.update(min=-OFFSET_LIMIT_MM, max=OFFSET_LIMIT_MM)
        elif name == "edge_margin":
            parameter.update(min=MIN_WALL_MM, max=max(EDGE_MARGIN_MAX_MM, 2 * value))
        result.append(parameter)
    return result


def _center(hole):
    """A hole's center: a circle's own, or the area centroid of a closed polyline."""
    if hole["type"] == "circle":
        return tuple(hole["center"])
    points = hole["points"]
    pairs = list(zip(points, points[1:] + points[:1]))
    crosses = [x0 * y1 - x1 * y0 for (x0, y0), (x1, y1) in pairs]
    area = sum(crosses) / 2
    return (sum((x0 + x1) * c for ((x0, _), (x1, _)), c in zip(pairs, crosses)) / (6 * area),
            sum((y0 + y1) * c for ((_, y0), (_, y1)), c in zip(pairs, crosses)) / (6 * area))


def _opened_offset(hole, matching):
    """How far what is left of an opened hole on the matching outline is from the original hole, or None.

    A round hole leaves an arc with its exact center (at whatever diameter it now has); a shaped hole
    keeps its own corners, which are fixed data in the program.
    """
    if hole["type"] == "circle":
        return min((math.dist(hole["center"], arc["center"]) for arc in matching["outline_arcs"]), default=None)
    return min(math.dist(corner, point) for corner in hole["points"] for point in matching["outline"])


def hole_alignment(original, matching, within=ALIGNED_WITHIN_MM):
    """How the matching part's holes line up with the original's, both as built top-face profiles.

    Holes pair up closest first, so a missing hole cannot take another hole's partner. A hole an inward
    offset has opened into the edge is not a closed hole any more, but its center is still where it should
    be: it counts as aligned and as a breakout. A hole left entirely outside the outline counts as neither.
    {"aligned": count, "total": original holes, "max_offset_mm": largest center offset, "breakouts": count}.
    """
    distances = sorted((math.dist(_center(a), _center(b)), i, j) for i, a in enumerate(original["holes"])
                       for j, b in enumerate(matching["holes"]))
    used_original, used_matching, offsets = set(), set(), []
    for distance, i, j in distances:
        if i not in used_original and j not in used_matching:
            used_original.add(i)
            used_matching.add(j)
            offsets.append(distance)
    breakouts = 0
    for i, hole in enumerate(original["holes"]):
        offset = None if i in used_original else _opened_offset(hole, matching)
        if offset is not None and offset <= within:
            offsets.append(offset)
            breakouts += 1
    return {"aligned": sum(offset <= within for offset in offsets), "total": len(original["holes"]),
            "max_offset_mm": round(max(offsets), 3) if offsets else None, "breakouts": breakouts}
