"""Baseline without a language model: extrude the measured outline polygon and cut the holes.

Writes a build_part() program straight from the measurement table: every corner
and every hole is its own parameter. It reproduces the measured shape but
carries no design intent (no shared hole diameter, no symmetry, no edge margins);
it is the yardstick for the model's candidates.
"""


def baseline_code(table, thickness=3.0):
    corners = table["outline"]["polygon_mm"]
    holes = table["holes"]
    arguments = [f"    thickness={thickness!r},"]
    arguments += [f"    corner{i}_u={u!r}, corner{i}_v={v!r}," for i, (u, v) in enumerate(corners, 1)]
    arguments += [f"    hole{i}_u={h['center_from_part_center_mm'][0]!r}, hole{i}_v={h['center_from_part_center_mm'][1]!r}, "
                  f"hole{i}_diameter={h['diameter_mm']!r}," for i, h in enumerate(holes, 1)]
    corner_list = ", ".join(f"(corner{i}_u, corner{i}_v)" for i in range(1, len(corners) + 1))
    hole_list = ", ".join(f"(hole{i}_u, hole{i}_v, hole{i}_diameter)" for i in range(1, len(holes) + 1))
    return "\n".join([
        '"""Baseline: measured outline extruded, holes cut. Generated by baseline_cad.py."""',
        "import cadquery as cq",
        "",
        "",
        "def build_part(",
        *arguments,
        "):",
        f"    part = cq.Workplane(\"XY\").polyline([{corner_list}]).close().extrude(thickness)",
        f"    for u, v, diameter in [{hole_list}]:",
        "        cylinder = cq.Workplane(\"XY\", origin=(u, v, -1)).circle(diameter / 2).extrude(thickness + 2)",
        "        part = part.cut(cylinder)",
        "    return part",
        "",
    ])
