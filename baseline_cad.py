"""Baseline without a language model: extrude the measured outline polygon and cut the holes.

Writes a build_part() program straight from the measurement table: every corner
and every hole dimension is its own parameter. Circles, rectangles, slots and
polygon holes are cut from their measured numbers. It reproduces the measured
shape but carries no design intent (no shared hole diameter, no symmetry, no
edge margins); it is the yardstick for the model's candidates.
"""


def _hole(i, hole):
    """(argument lines, cutter expression) for one hole."""
    u, v = hole["center_from_part_center_mm"]
    name = f"hole{i}"
    at = f"cq.Workplane(\"XY\", origin=({name}_u, {name}_v, -1))"
    shape = hole["shape"]
    if shape == "circle":
        arguments = [f"    {name}_u={u!r}, {name}_v={v!r}, {name}_diameter={hole['diameter_mm']!r},"]
        return arguments, f"{at}.circle({name}_diameter / 2).extrude(thickness + 2)"
    if shape in ("rectangle", "slot", "ellipse"):
        arguments = [f"    {name}_u={u!r}, {name}_v={v!r}, {name}_length={hole['length_mm']!r}, "
                     f"{name}_width={hole['width_mm']!r}, {name}_angle={hole['angle_deg']!r},"]
        sketch = {"rectangle": f"rect({name}_length, {name}_width)",
                  "slot": f"slot2D({name}_length, {name}_width)",
                  "ellipse": f"ellipse({name}_length / 2, {name}_width / 2)"}[shape]
        return arguments, f"{at}.transformed(rotate=(0, 0, {name}_angle)).{sketch}.extrude(thickness + 2)"
    corners = hole["polygon_mm"]
    arguments = [f"    {name}_corner{j}_u={cu!r}, {name}_corner{j}_v={cv!r}," for j, (cu, cv) in enumerate(corners, 1)]
    points = ", ".join(f"({name}_corner{j}_u, {name}_corner{j}_v)" for j in range(1, len(corners) + 1))
    return arguments, f"cq.Workplane(\"XY\", origin=(0, 0, -1)).polyline([{points}]).close().extrude(thickness + 2)"


def baseline_code(table, thickness=3.0):
    corners = table["outline"]["polygon_mm"]
    arguments = [f"    thickness={thickness!r},"]
    arguments += [f"    corner{i}_u={u!r}, corner{i}_v={v!r}," for i, (u, v) in enumerate(corners, 1)]
    cutters = []
    for i, hole in enumerate(table["holes"], 1):
        hole_arguments, cutter = _hole(i, hole)
        arguments += hole_arguments
        cutters.append(f"    part = part.cut({cutter})")
    corner_list = ", ".join(f"(corner{i}_u, corner{i}_v)" for i in range(1, len(corners) + 1))
    return "\n".join([
        '"""Baseline: measured outline extruded, holes cut. Generated by baseline_cad.py."""',
        "import cadquery as cq",
        "",
        "",
        "def build_part(",
        *arguments,
        "):",
        f"    part = cq.Workplane(\"XY\").polyline([{corner_list}]).close().extrude(thickness)",
        *cutters,
        "    return part",
        "",
    ])
